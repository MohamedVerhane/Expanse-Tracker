export function translate(locale: Locale, key: string, params?: Record<string, string>): string {
  const value = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? "");
}

export function translateCategory(locale: Locale, slug: string, fallback: string): string {
  const key = `category.${slug}`;
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? fallback;
}
